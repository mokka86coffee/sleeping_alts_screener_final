"""Действие вместо вердикта (Р-27). Что делать с монетой сегодня.

Зачем понадобился отдельный слой. Скринер научился отвечать «готово ли»
(Р-1, Р-6), «жива ли фигура» (Р-25) и «пора ли смотреть» (Р-11). Но
между «пора смотреть» и «выйти» лежит целый набор действий, которыми
человек на самом деле пользуется: сократить, добрать, захеджировать,
переждать. Правило, знающее только «держать / выйти», заставляет
выбирать из двух крайностей там, где уместна середина.

И группировка зала теперь та же: БРАТЬ · ДЕРЖАТЬ · ВЫХОДИТЬ — это не
три списка монет, а три вопроса, на которые у нас уже есть слои.

ГОРИЗОНТ ВЫХОДА ЗАВИСИТ ОТ РАЗМЕРА ТРАНША, а не задан одним числом.
Пять дней хватает мелкому разлоку; перед крупным инсайдерским выходят
за неделю-две, потому что раздача начинается заранее и идёт долго.
Единая константа тут была моей ошибкой: она приравнивала транш на
процент флоата к траншу на четверть.

Чего слой НЕ делает: не открывает и не закрывает позиции, не считает
доходность и не спорит со стопом. Он называет действие и причину —
решение остаётся за человеком, как и везде в этом документе.
"""

from __future__ import annotations

# ── Ступени транша по доле от того, что В ОБОРОТЕ ──
# Знаменатель — флоат, а не эмиссия: цену двигает предложение, которое
# реально торгуется. Четыре режима, границы названы человеком:
#   < 5%  — фон. Не повод для действия: такой объём переваривается
#           дневным оборотом и до цены почти не доходит.
#   5–15% — заметно, но не смертельно. Уменьшить долю и пережить.
#   15–25% — существенно: раздача продавит, держать полную позицию
#           незачем.
#   > 25% — выход обязателен. Четверть свободного обращения разом —
#           это не давление на цену, а смена её масштаба.
# Горизонт растёт вместе с долей: крупную раздачу начинают заранее и
# ведут долго, мелкую — в день события.
#
# ДВА ГОРИЗОНТА, А НЕ ОДИН. Предупреждать надо раньше, чем действовать:
# про транш свыше четверти обращения полезно знать за месяц — чтобы не
# набирать позицию, которую придётся закрывать, и чтобы выход не стал
# внезапным. Само действие остаётся на двух неделях: раньше выходить
# незачем, до раздачи ещё живёт своя жизнь. Склеенные в одно число, эти
# горизонты заставляли выбирать между «узнать поздно» и «выйти рано».
#
#            доля         действие      действовать   знать
UNLOCK_TIERS = (
    (25.0, "выйти",     14, 30),
    (15.0, "сократить", 12, 20),
    (5.0,  "сократить",  7, 12),
    (0.0,  "держать",    5,  5),
)
EXIT_DAYS_SMALL = 5

# Добор после сквиза: плечо слито, а фигура жива. Порог удержания —
# зеркало связки (Р-12), где опасным считается ≥70% удержания.
REFILL_OI_HELD_MAX = 45.0

# Хеджировать имеет смысл, когда впереди дата с непредсказуемым
# знаком. Две ступени: макро-событие и выходные.
HEDGE_MACRO_DAYS = 2


def unlock_tier(share_pct: float | None) -> dict:
    """Режим транша по его доле от обращения: действие и горизонт.

    Доля неизвестна — самая мягкая ступень с горизонтом в пять дней:
    отметить и посмотреть глазами. Выносить приговор по величине,
    которой нет, нельзя (то же правило, что у пустых недель в fuel).
    """
    try:
        share = float(share_pct)
    except (TypeError, ValueError):
        return {"act": "держать", "days": EXIT_DAYS_SMALL,
                "warn": EXIT_DAYS_SMALL, "share": None}
    for edge, act, days, warn in UNLOCK_TIERS:
        if share >= edge:
            return {"act": act, "days": days, "warn": warn, "share": share}
    return {"act": "держать", "days": EXIT_DAYS_SMALL,
            "warn": EXIT_DAYS_SMALL, "share": share}


def unlock_horizon(share_pct: float | None) -> int:
    """За сколько дней до транша он начинает влиять на решение."""
    return unlock_tier(share_pct)["days"]


def decide(star: dict, permission: dict | None = None,
           held: bool = False) -> dict:
    """Одно действие на монету. Одно, а не список.

    Порядок проверок — это и есть приоритет: сначала то, что нельзя
    отложить (выход), потом уменьшение риска, потом добавление. Список
    из трёх действий читался бы как «делай что-нибудь» и не помогал
    бы решать.

    held — открыта ли позиция (из журнала решений, Р-14). Без неё
    монета может только попасть в «брать»: советовать «сократить» по
    монете, которой у нас нет, бессмысленно.

    Возвращает {"act", "why", "group"}. group — колонка зала:
    "take" / "hold" / "exit".
    """
    parts = ((permission or {}).get("parts") or {})
    cal = (parts.get("calendar") or {}).get("items") or []

    # ── Транш: горизонт по размеру ──
    days = star.get("unlockDays")
    try:
        days_i = int(days) if days is not None else None
    except (TypeError, ValueError):
        days_i = None
    share = star.get("unlockPctFloat")
    tier = unlock_tier(share)
    unlock_near = days_i is not None and 0 <= days_i <= tier["days"]
    # Знать раньше, чем действовать: транш уже виден, но действие ещё
    # не назрело. Такая монета остаётся в «держать» — с примечанием.
    unlock_ahead = (days_i is not None and tier["act"] != "держать"
                    and tier["days"] < days_i <= tier["warn"])
    ahead_note = ""
    if unlock_ahead:
        ahead_note = (f"через {days_i} дн транш {tier['share']:.0f}% "
                      "обращения — выход планировать заранее, позицию не "
                      "наращивать")

    # ── 1. Транш: действие по ступени доли ──
    if held and unlock_near:
        share_s = (f"{tier['share']:.0f}% обращения"
                   if tier["share"] is not None else "доля не заполнена")
        if tier["act"] == "выйти":
            return {"act": "выйти", "group": "exit",
                    "why": f"транш {share_s} через {days_i} дн — четверть "
                           "обращения разом меняет масштаб цены"}
        if tier["act"] == "сократить":
            hard = tier["share"] is not None and tier["share"] >= 15.0
            return {"act": "сократить", "group": "exit",
                    "why": (f"транш {share_s} через {days_i} дн — "
                            + ("раздача продавит, полной позиции незачем"
                               if hard else
                               "уменьшить долю и пережить"))}
        # Меньше пяти процентов — фон: отмечаем, но действия не даём.
        # Такой объём переваривается дневным оборотом.

    # ── 2. Выход по истощению (Р-11): поток и крупные продажи ──
    if held and (star.get("exitWhy") or []):
        return {"act": "сократить", "group": "exit",
                "why": (star.get("exitWhy") or [""])[0]}

    # ── 3. Фигура распалась (Р-25) ──
    gap = star.get("aliveGapDays")
    if held and gap is not None and gap > 3:
        return {"act": "выйти", "group": "exit",
                "why": f"фигура не подтверждается {gap:.0f} дн — "
                       "это не ожидание, а распад"}

    # ── 4. Хедж перед датой с непредсказуемым знаком ──
    if held:
        for it in cal:
            if it.get("kind") in ("risk", "macro") and not it.get("running") \
                    and int(it.get("days") or 99) <= HEDGE_MACRO_DAYS:
                return {"act": "хеджировать", "group": "hold",
                        "why": f"{it.get('title')} через "
                               f"{int(it.get('days') or 0)} дн — знак "
                               "непредсказуем, снять риск на событие"}
        if (parts.get("weekend") or {}).get("warn"):
            return {"act": "хеджировать", "group": "hold",
                    "why": "выходные — тонкий стакан, прокол проходит глубже"}

    # ── 5. Добор после сквиза: плечо слито, фигура жива ──
    held_pct = star.get("oiHeld")
    if held and held_pct is not None:
        try:
            empty = float(held_pct) <= REFILL_OI_HELD_MAX
        except (TypeError, ValueError):
            empty = False
        alive = gap is None or gap <= 3
        if empty and alive and not (parts.get("cascade") or {}).get("warn"):
            return {"act": "добрать", "group": "hold",
                    "why": f"плечо слито (держится {float(held_pct):.0f}%), "
                           "фигура жива — движение пойдёт с пустого"}

    if held:
        return {"act": "держать", "group": "hold", "why": ahead_note}

    # ── 6. Без позиции: брать или ждать ──
    if star.get("linkNote"):
        return {"act": "мимо", "group": "take",
                "why": "связка плеча с траншем — вход в чужую раздачу"}
    if unlock_near and tier["act"] != "держать":
        # Входить перед раздачей — покупать у того, кто выходит.
        return {"act": "мимо", "group": "take",
                "why": f"транш {tier['share']:.0f}% обращения через "
                       f"{days_i} дн"}
    if unlock_ahead:
        # Знание пришло раньше действия: входить ещё можно, но зная
        # срок и меньшим размером — история кончится этой датой.
        return {"act": "ждать", "group": "take", "why": ahead_note}
    phase = (star.get("phase") or {}).get("k")
    if phase == "go" and (gap is None or gap <= 3):
        size = (star.get("size") or {}).get("tier") or ""
        return {"act": "брать", "group": "take",
                "why": ("размером " + size) if size else ""}
    return {"act": "ждать", "group": "take",
            "why": (star.get("phase") or {}).get("a") or ""}
