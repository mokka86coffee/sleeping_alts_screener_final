"""Действие вместо вердикта (Р-27). Что делать с монетой сегодня.

Зачем понадобился отдельный слой. Скринер научился отвечать «готово ли»
(Р-1, Р-6), «жива ли фигура» (Р-25) и «пора ли смотреть» (Р-11). Но
между «пора смотреть» и «выйти» лежит целый набор действий, которыми
человек на самом деле пользуется: сократить, добрать, захеджировать,
переждать. Правило, знающее только «держать / выйти», заставляет
выбирать из двух крайностей там, где уместна середина.

И группировка зала теперь та же: БРАТЬ · ДЕРЖАТЬ · ВЫХОДИТЬ — это не
три списка монет, а три вопроса, на которые у нас уже есть слои.

ГОРИЗОНТ ВЫХОДА ЗАВИСИТ ОТ РАЗМЕРА ТРАНША, а не задан одним числом.
Пять дней хватает мелкому разлоку; перед крупным инсайдерским выходят
за неделю-две, потому что раздача начинается заранее и идёт долго.
Единая константа тут была моей ошибкой: она приравнивала транш на
процент флоата к траншу на четверть.

Чего слой НЕ делает: не открывает и не закрывает позиции, не считает
доходность и не спорит со стопом. Он называет действие и причину —
решение остаётся за человеком, как и везде в этом документе.
"""

from __future__ import annotations

# ── Ступени транша по доле от того, что В ОБОРОТЕ ──
# Знаменатель — флоат, а не эмиссия: цену двигает предложение, которое
# реально торгуется. Четыре режима, границы названы человеком:
#   < 5%  — фон. Не повод для действия: такой объём переваривается
#           дневным оборотом и до цены почти не доходит.
#   5–15% — заметно, но не смертельно. Уменьшить долю и пережить.
#   15–25% — существенно: раздача продавит, держать полную позицию
#           незачем.
#   > 25% — выход обязателен. Четверть свободного обращения разом —
#           это не давление на цену, а смена её масштаба.
# Горизонт растёт вместе с долей: крупную раздачу начинают заранее и
# ведут долго, мелкую — в день события.
#
# ДВА ГОРИЗОНТА, А НЕ ОДИН. Предупреждать надо раньше, чем действовать:
# про транш свыше четверти обращения полезно знать за месяц — чтобы не
# набирать позицию, которую придётся закрывать, и чтобы выход не стал
# внезапным. Само действие остаётся на двух неделях: раньше выходить
# незачем, до раздачи ещё живёт своя жизнь. Склеенные в одно число, эти
# горизонты заставляли выбирать между «узнать поздно» и «выйти рано».
#
#            доля         действие      действовать   знать
UNLOCK_TIERS = (
    (25.0, "выйти",     14, 30),
    (15.0, "сократить", 12, 20),
    (5.0,  "сократить",  7, 12),
    (0.0,  "держать",    5,  5),
)
EXIT_DAYS_SMALL = 5

# Добор после сквиза: плечо слито, а фигура жива. Порог удержания —
# зеркало связки (Р-12), где опасным считается ≥70% удержания.
REFILL_OI_HELD_MAX = 45.0

# Хеджировать имеет смысл, когда впереди дата с непредсказуемым
# знаком. Две ступени: макро-событие и выходные.
HEDGE_MACRO_DAYS = 2


def unlock_tier(share_pct: float | None) -> dict:
    """Режим транша по его доле от обращения: действие и горизонт.

    Доля неизвестна — самая мягкая ступень с горизонтом в пять дней:
    отметить и посмотреть глазами. Выносить приговор по величине,
    которой нет, нельзя (то же правило, что у пустых недель в fuel).
    """
    try:
        share = float(share_pct)
    except (TypeError, ValueError):
        return {"act": "держать", "days": EXIT_DAYS_SMALL,
                "warn": EXIT_DAYS_SMALL, "share": None}
    for edge, act, days, warn in UNLOCK_TIERS:
        if share >= edge:
            return {"act": act, "days": days, "warn": warn, "share": share}
    return {"act": "держать", "days": EXIT_DAYS_SMALL,
            "warn": EXIT_DAYS_SMALL, "share": share}


def unlock_horizon(share_pct: float | None) -> int:
    """За сколько дней до транша он начинает влиять на решение."""
    return unlock_tier(share_pct)["days"]


def _decide(star: dict, permission: dict | None = None,
           held: bool = False) -> dict:
    """Одно действие на монету. Одно, а не список.

    Порядок проверок — это и есть приоритет: сначала то, что нельзя
    отложить (выход), потом уменьшение риска, потом добавление. Список
    из трёх действий читался бы как «делай что-нибудь» и не помогал
    бы решать.

    held — открыта ли позиция В ТОРГОВОЙ КНИГЕ (журнал предположений).
    Не в журнале лидеров: журнал есть у обоих подходов, а правила
    решают только за трейдинг. Без позиции монета может попасть только
    в «брать» — советовать «сократить» по тому, чего нет, бессмысленно.

    Возвращает {"act", "why", "group"} — группа ТОРГОВОЙ книги:
    "take" (взять сейчас) / "trade" (в работе) / "exit" (выходить).
    Инвестиционная книга HOLD сюда не приходит вовсе: к ней правила
    не применяются, и решать за неё нечего.
    """
    parts = ((permission or {}).get("parts") or {})
    cal = (parts.get("calendar") or {}).get("items") or []

    # ── Транш: горизонт по размеру ──
    days = star.get("unlockDays")
    try:
        days_i = int(days) if days is not None else None
    except (TypeError, ValueError):
        days_i = None
    share = star.get("unlockPctFloat")
    tier = unlock_tier(share)
    unlock_near = days_i is not None and 0 <= days_i <= tier["days"]
    # Знать раньше, чем действовать: транш уже виден, но действие ещё
    # не назрело. Такая монета остаётся в «держать» — с примечанием.
    unlock_ahead = (days_i is not None and tier["act"] != "держать"
                    and tier["days"] < days_i <= tier["warn"])
    ahead_note = ""
    if unlock_ahead:
        ahead_note = (f"через {days_i} дн транш {tier['share']:.0f}% "
                      "обращения — выход планировать заранее, позицию не "
                      "наращивать")

    # ── 1. Транш: действие по ступени доли ──
    if held and unlock_near:
        share_s = (f"{tier['share']:.0f}% обращения"
                   if tier["share"] is not None else "доля не заполнена")
        if tier["act"] == "выйти":
            return {"act": "выйти", "group": "exit",
                    "why": f"транш {share_s} через {days_i} дн — четверть "
                           "обращения разом меняет масштаб цены"}
        if tier["act"] == "сократить":
            hard = tier["share"] is not None and tier["share"] >= 15.0
            return {"act": "сократить", "group": "exit",
                    "why": (f"транш {share_s} через {days_i} дн — "
                            + ("раздача продавит, полной позиции незачем"
                               if hard else
                               "уменьшить долю и пережить"))}
        # Меньше пяти процентов — фон: отмечаем, но действия не даём.
        # Такой объём переваривается дневным оборотом.

    # ── 2. Выход по истощению (Р-11): поток и крупные продажи ──
    if held and (star.get("exitWhy") or []):
        return {"act": "сократить", "group": "exit",
                "why": (star.get("exitWhy") or [""])[0]}

    # ── 3. Фигура распалась (Р-25) ──
    gap = star.get("aliveGapDays")
    if held and gap is not None and gap > 3:
        return {"act": "выйти", "group": "exit",
                "why": f"фигура не подтверждается {gap:.0f} дн — "
                       "это не ожидание, а распад"}

    # ── 4. Хедж перед датой с непредсказуемым знаком ──
    if held:
        for it in cal:
            if it.get("kind") in ("risk", "macro") and not it.get("running") \
                    and int(it.get("days") or 99) <= HEDGE_MACRO_DAYS:
                return {"act": "хеджировать", "group": "trade",
                        "why": f"{it.get('title')} через "
                               f"{int(it.get('days') or 0)} дн — знак "
                               "непредсказуем, снять риск на событие"}
        if (parts.get("weekend") or {}).get("warn"):
            return {"act": "хеджировать", "group": "trade",
                    "why": "выходные — тонкий стакан, прокол проходит глубже"}

    # ── 4б. Добор ОСТАТКА ПЛАНА входа ──
    # Хвост дробного входа добирается по УЛУЧШЕНИЮ, а не по таймеру:
    # добор по расписанию ничем не отличался бы от входа всей суммой,
    # только с лишним шагом. Условие улучшения — окно стало чище, чем
    # было при первой части, и цена не убежала: догонять собственный
    # вход дороже на пятнадцать процентов смысла нет.
    book = star.get("book") or {}
    plan_total = float((star.get("entry") or {}).get("total") or 0.0)
    got = float(book.get("usd") or 0.0)
    if held and plan_total and got and got < plan_total * 0.95:
        warn_now = int((permission or {}).get("warnCount") or 0)
        px_now = float(star.get("px") or 0.0)
        px_in = float(book.get("px") or 0.0)
        ran = (px_in > 0 and px_now > 0 and px_now / px_in - 1 > 0.15)
        if warn_now <= 1 and not ran:
            left = round(plan_total - got)
            return {"act": "добрать", "group": "trade",
                    "why": f"окно очистилось — добрать остаток плана ${left}"}

    # ── 5. Добор после сквиза: плечо слито, фигура жива ──
    held_pct = star.get("oiHeld")
    if held and held_pct is not None:
        try:
            empty = float(held_pct) <= REFILL_OI_HELD_MAX
        except (TypeError, ValueError):
            empty = False
        alive = gap is None or gap <= 3
        if empty and alive and not (parts.get("cascade") or {}).get("warn"):
            return {"act": "добрать", "group": "trade",
                    "why": f"плечо слито (держится {float(held_pct):.0f}%), "
                           "фигура жива — движение пойдёт с пустого"}

    if held:
        # Новая монета прогона — это и есть «взять сейчас»: она только
        # что попала в журнал, позиции по ней ещё нет. Дальше та же
        # монета живёт в «держать», пока не появится повод действовать.
        if star.get("firstRun") or (star.get("days") is not None
                                    and int(star.get("days") or 0) <= 0):
            size = (star.get("size") or {}).get("tier") or ""
            return {"act": "брать", "group": "take",
                    "why": ("размером " + size) if size else ""}
        return {"act": "держать", "group": "trade", "why": ahead_note}

    # ── 6. Без позиции: брать или ждать ──
    # ВХОД — СОБЫТИЕ, А НЕ СОСТОЯНИЕ (правка 23.08).
    # Раньше условием было «фаза go и фигура жива» — состояние, под
    # которое подходит почти весь журнал: вся альта на дне с живыми
    # фигурами. На первом же прогоне книга открыла тридцать две позиции
    # разом и просто повторила HOLD с задержкой в прогон. Сравнивать
    # два подхода бессмысленно, если второй копирует первый.
    # Событие — это ПОЯВЛЕНИЕ монеты в журнале (или возврат после
    # выхода из книги). «Стоит пятый день с живой фигурой» событием не
    # является.
    if star.get("linkNote"):
        return {"act": "мимо", "group": "take",
                "why": "связка плеча с траншем — вход в чужую раздачу"}
    if unlock_near and tier["act"] != "держать":
        # Входить перед раздачей — покупать у того, кто выходит.
        return {"act": "мимо", "group": "take",
                "why": f"транш {tier['share']:.0f}% обращения через "
                       f"{days_i} дн"}
    if unlock_ahead:
        # Знание пришло раньше действия: входить ещё можно, но зная
        # срок и меньшим размером — история кончится этой датой.
        return {"act": "ждать", "group": "take", "why": ahead_note}
    fresh = bool(star.get("firstRun")) or (
        star.get("days") is not None and int(star.get("days") or 0) <= 0)
    # ВОЗВРАТ ПОСЛЕ ВЫХОДА — вторая половина события входа. В правиле
    # она записана с самого начала («появление в журнале ИЛИ возврат
    # после выхода»), а в коде не жила: вышедшая монета получала
    # «ждать» навсегда. Возврат — не «фигура всё ещё жива» (это то
    # самое состояние, с которого Р-30 начинался), а «ПРИЧИНА ВЫХОДА
    # СНЯТА»: поток чист (exitWhy пуст), фигура подтверждается; транш
    # и связка проверены выше и закрывают вход своими «мимо»/«ждать».
    returned = (bool(star.get("wasClosed"))
                and not (star.get("exitWhy") or []))
    phase = (star.get("phase") or {}).get("k")

    if (fresh or returned) and phase == "go" and (gap is None or gap <= 3):
        plan = star.get("entry") or {}
        parts = int(plan.get("parts") or 1)
        first = plan.get("first")
        why = plan.get("why") or ""
        if parts > 1 and first:
            why = f"вход {parts} частями, первая ${first:.0f} — " + why
        elif first:
            why = f"вход одной суммой ${first:.0f}"
        if returned and not fresh:
            why = ("возврат: причина выхода снята — " + why) if why else \
                  "возврат: причина выхода снята, фигура подтверждается"
        return {"act": "брать", "group": "take", "why": why}

    if fresh:
        return {"act": "ждать", "group": "take",
                "why": "новая в журнале, но фигура не подтверждена"}
    return {"act": "ждать", "group": "take", "why": wait_reason(star)}


# ── Почему ждать: возражения ─────────────────────────────────
# Было: сюда подставлялась ФАЗА («ровный рост · ждать сквиза»).
# Фаза отвечает, где монета в своём цикле, а не почему нельзя
# входить СЕЙЧАС, — и одна и та же строка стояла у монет с разной
# причиной отказа. «Ждать» без причины — приказ; с причиной — довод,
# который можно оспорить.
#
# Каждая проверка даёт ТРИ вещи: короткую запись (наверх карточки),
# развёрнутую (вниз, рядом со стратегией) и условие снятия — что
# именно должно измениться, чтобы запрет перестал действовать.
# Порядок = сила возражения. Наверху показываем первое, внизу все:
# решение принимается по самому жёсткому, но знать надо обо всех.

# Ниже этой капитализации свой же вход двигает цену: даже верный
# сценарий не исполнится по расчёту.
THIN_BOOK_USD = 3_000_000
# Опора ближе этой доли ATR не отделяет ошибку от обычного шума.
STOP_NOISE_ATR = 0.5


def _objections(star: dict) -> list[dict]:
    """Все сработавшие возражения по монете, от жёсткого к мягкому.

    Считается ОДИН раз и прикладывается к ЛЮБОМУ решению — раньше
    разбор жил внутри ветки «ждать», и монета с открытой позицией
    («держать», «хеджировать», «сократить») получала одну строку без
    объяснения. Перекос был обратный здравому смыслу: развёрнутый
    ответ доставался тому, у кого денег в монете НЕТ, а тому, у кого
    позиция открыта, — нет. Цена ошибки как раз во втором случае выше.

    Часть проверок общая, часть включается только при позиции: пока
    монета не куплена, «плечо не разгружено» не возражение, а
    наблюдение.
    """
    out: list[dict] = []
    held = bool((star.get("book") or {}).get("usd"))

    def _f(d, k):
        try:
            return float((d or {}).get(k))
        except (TypeError, ValueError):
            return None

    # 1. Размер важнее правоты: тонкую книгу не исполнить по расчёту.
    cap = _f(star, "capUsd") or _f(star.get("raw") or {}, "mcap_usd") or 0.0
    if 0 < cap < THIN_BOOK_USD:
        out.append({
            "short": f"книга тонка (${cap/1e3:.0f}K)",
            "full": (f"капитализация ${cap/1e3:.0f}K — свой же вход и выход "
                     f"двигают цену; проскальзывание съест разницу между "
                     f"расчётом и результатом, стоп исполнится не там, где стоит"),
            "lift": "снимется только ростом книги — ждать тут нечего"})

    lv = star.get("levels") or {}
    below, above = (lv.get("below") or {}), (lv.get("above") or {})
    batr, aatr = _f(below, "atr"), _f(above, "atr")

    # 2. Стоп внутри шума.
    if batr is not None and 0 < batr < STOP_NOISE_ATR:
        out.append({
            "short": f"опора в {batr:.1f} ATR",
            "full": (f"опора всего в {batr:.1f} ATR под ценой — это шум, "
                     f"а не защита: стоп под ней вынесет обычным колебанием, "
                     f"без движения против позиции"),
            "lift": "снимется, когда опора отойдёт дальше 0.5 ATR"})

    # 3. Тест Вайкоффа не пройден.
    wt = star.get("wyckoffTest") or {}
    if wt.get("note") and not wt.get("tested"):
        vr = wt.get("volRatio")
        tail = f" — {float(vr)*100:.0f}% объёма прокола" if vr else ""
        out.append({
            "short": "второй заход не тише",
            "full": (f"второй заход к дну прошёл не тише первого{tail}: "
                     f"удержать уровень стоило столько же усилия, "
                     f"значит предложение не иссякло"),
            "lift": "снимется, когда заход к дну пройдёт тише прокола"})

    # 4. Ход сделан: до потолка ближе, чем до опоры.
    if aatr is not None and batr is not None and 0 < aatr < batr:
        out.append({
            "short": f"до потолка {aatr:.1f} ATR",
            "full": (f"до потолка {aatr:.1f} ATR, до опоры {batr:.1f} — "
                     f"риск больше остатка хода; отношение перевёрнуто, "
                     f"и сетап не созревает, а отработан"),
            "lift": "снимется откатом к зоне входа"})

    # 5. Транш в горизонте — тем острее, чем ближе.
    ud = star.get("unlockDays")
    try:
        ud = int(ud) if ud is not None else None
    except (TypeError, ValueError):
        ud = None
    if ud is not None and 0 <= ud <= UNLOCK_NEAR_DAYS:
        when = "сегодня" if ud == 0 else f"через {ud} дн"
        out.append({
            "short": f"транш {when}",
            "full": (f"разлок {when} — предложение приходит в стакан "
                     f"и встречает любой ход сверху; входить перед раздачей "
                     f"значит покупать у того, кто выходит"),
            "lift": "снимется после транша — по тому, забрали его или нет"})

    # ── Дальше только при ОТКРЫТОЙ позиции ──
    if not held:
        return out

    # 6. Плечо не разгрузилось: цена и открытый интерес разошлись.
    px, oi = _f(star, "stancePricePct"), _f(star, "stanceOiPct")
    if px is not None and oi is not None and px > 0 and oi > -LEV_UNLOAD_PCT:
        out.append({
            "short": "плечо не сброшено",
            "full": (f"цена ушла на {px:+.0f}%, а открытый интерес на "
                     f"{oi:+.0f}% — толпа, зашедшая на ходе, не вышла; "
                     f"этот навес висит НАД ценой и продаст вперёд вас"),
            "lift": f"снимется падением интереса за {LEV_UNLOAD_PCT:.0f}% "
                    f"при стоячей цене — это и есть вымывание"})
    return out


