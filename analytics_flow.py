"""FLOW · отбор, порядок и ключи семейства для потребителей отчёта.

Что здесь. Всё, что отвечает на вопросы «кто попал в FLOW», «в каком
они порядке», «кто лидер», «сколько монет в каждом подкейсе» — то
есть работа со СПИСКОМ найденных монет, а не с одной монетой.

Чего здесь нет. Собственно поиска сигнала: его делают detectors_flow*
и результат кладут в candidate.flow. Этот модуль ничего не
детектирует, он читает уже готовое поле и приводит его к виду,
удобному тому, кто показывает.

Почему отдельный модуль, а не «в рендере, где понадобилось». До
этого те же три вопроса решались независимо в трёх местах: отбор
`[c for c in candidates if c.flow]` был выписан в render_orbit.py и
render_dashboard.py, а «лидер FLOW» — максимум по score — существовал
ТРЕМЯ отдельными копиями (две в орбите, одна в дашборде). Пока
правило одно и простое, копии совпадают; в день, когда лидера начнут
выбирать иначе (скажем, с поправкой на возраст записи), разойдётся
только часть из них — молча, без падения и без строки в логе.
Заметить это можно лишь глазами, сверив два экрана между собой.

Порядок вызова значения не имеет: каждая функция считает от списка
кандидатов и ничего не запоминает. Именно поэтому «пересчитать
заново» здесь дешевле, чем передавать готовое между экранами, —
после переезда экранов в отдельные iframe передавать всё равно
некуда, у каждого документа своё окно.
"""

from __future__ import annotations

from core_models import Candidate
from analytics_metrics import base_symbol, card_data, fmt_cap

# Диспетчер семейства (detectors_flow.py) именует подкейсы с
# префиксом модуля: flow_hidden, flow_churn. Внутри семейства это
# правильно — имя совпадает с именем модуля и с ключами CASE_CAP.
# Наружу префикс смысла не несёт и ломает сопоставление по короткому
# ключу, поэтому режется ровно на границе: здесь.
CASE_PREFIX = "flow_"

# Русские имена подкейсов. Короткие: в чипе карточки длинная
# формулировка переносится на вторую строку и ломает сетку. Полные
# описания живут на ленте стратегии, здесь нужен ярлык.
#
# Почему в аналитике, а не среди помощников рендера, где словарь
# пролежал один шаг. Подпись подкейса попадает В ДАННЫЕ звезды, а не
# только в разметку, — и собирает эти данные analytics_stars, которому
# импортировать рендер нельзя вовсе. Держать словарь в рендере значило
# бы либо нарушить это правило, либо завести вторую копию подписей на
# стороне аналитики.
#
# ВНИМАНИЕ на несовпадение с FLOW_NODES в render_common: ключ подкейса
# плеча здесь "leverage" (так его называет detectors_flow), а узел в
# ленте назван "lever". Из-за этого счётчик у узла плеча никогда не
# находит свои монеты. Не правлю заодно: правка меняет и подпись узла
# на экране, она берётся из того же ключа.
CASE_RU = {
    "hidden": "скрытый набор",
    "spring": "сжатие",
    "churn": "поглощение",
    "fuel": "путь свободен",
    "dormant": "спячка",
    "taker": "смена агрессора",
    "leverage": "перекос плеча",
}


def case_key(raw: str) -> str:
    """Короткий ключ подкейса: flow_hidden → hidden.

    Публичная и единственная: по этому ключу и дашборд, и орбита, и
    карточка потока ищут подпись, цвет и позицию узла в ленте. Две
    разные реализации среза префикса означали бы два разных ключа для
    одной монеты в двух местах экрана.
    """
    return str(raw or "").removeprefix(CASE_PREFIX)


def case_of(c: Candidate) -> str:
    """Сырое имя подкейса монеты, как его записал диспетчер.

    Именно сырое, с префиксом: короткий ключ получают через
    case_key(). Разделено, потому что часть мест сверяется с ключами
    самого семейства (где префикс есть), а часть — с подписями и
    узлами ленты (где его нет).
    """
    return str((c.flow or {}).get("case", "") or "")


def flow_candidates(candidates: list[Candidate]) -> list[Candidate]:
    """Монеты, у которых семейство нашло сигнал. Порядок исходный."""
    return [c for c in candidates if c.flow]


# Р-6/Р-12: пороги «своих обстоятельств» монеты. Окно транша то же,
# что у календаря частокола (Р-7) и связки (Р-12) — один горизонт
# внимания на весь проект.
UNLOCK_NEAR_DAYS = 5
LINK_OI_RISE_X = 1.5
LINK_OI_HELD_PCT = 70.0


def flow_order(candidates: list[Candidate]) -> list[Candidate]:
    """Монеты FLOW в порядке отчёта: по убыванию score.

    Порядок спрашивают уже в нескольких местах — сам список, подпись
    позиции на карточке, номер звезды на орбите. Два независимых
    sorted разошлись бы при первой правке правила, и номер на
    карточке перестал бы совпадать со строкой в списке. Такое
    расхождение не падает и не логируется — его замечают глазами
    через неделю.
    """
    return sorted(
        flow_candidates(candidates),
        key=lambda c: -(getattr(c, "score", 0) or 0),
    )


def coin_window(c: Candidate) -> dict:
    """Р-6: окно КОНКРЕТНОЙ монеты. Не вердикт, а причина словами.

    Разрешение рынка (Р-1) действует на всю выборку одинаково и живёт
    в строке брифа. Здесь другое: у монеты бывают СВОИ обстоятельства,
    которых нет у соседа по списку — транш через три дня, связка плеча
    с траншем, отыгранная фигура. Список из-за них не пустеет и по
    скору не переупорядочивается: меняются подпись и порядок показа.

    Аналогия из нулевого раздела: поездку не отменяют из-за дождя в
    первые дни — кладут зонт. Монета с разлоком через три дня и монета
    с чистым горизонтом обе остаются в списке, но человек видит
    разницу ДО того, как принимает решение.

    Возвращает {"open": bool, "why": str}. Пустая причина при open —
    норма: сказать нечего, потому что мешать нечему.
    """
    raw = getattr(c, "raw", None) or {}
    flow = getattr(c, "flow", None) or {}

    u = raw.get("unlocks") or {}
    days = u.get("next_days")
    if days is not None:
        try:
            days_i = int(days)
        except (TypeError, ValueError):
            days_i = -1
        if 0 <= days_i <= UNLOCK_NEAR_DAYS:
            # Связка (Р-12) сильнее одиночного транша и заслуживает
            # своей формулировки: плечо сверху и предложение снизу.
            oi = (flow.get("context") or {}).get("oi_hist") or {}
            rise = oi.get("rise_x")
            held = oi.get("held_pct")
            try:
                linked = (rise is not None and held is not None
                          and float(rise) >= LINK_OI_RISE_X
                          and float(held) >= LINK_OI_HELD_PCT)
            except (TypeError, ValueError):
                linked = False
            when = ("сегодня" if days_i == 0 else
                    "завтра" if days_i == 1 else f"через {days_i} дн")
            return {"open": False,
                    "why": (f"плечо набрано, транш {when}" if linked
                            else f"транш {when}")}

    case = str(flow.get("case") or "")
    if ((flow.get("cases") or {}).get(case) or {}).get("late"):
        return {"open": False, "why": "фигура отыграна"}

    return {"open": True, "why": ""}


def flow_order_windowed(candidates: list[Candidate]) -> list[Candidate]:
    """Порядок показа с учётом окна монеты (Р-6).

    Строится НА flow_order, а не вместо него: сначала прежний порядок
    по скору, затем УСТОЙЧИВОЕ разделение на две группы — открытое
    окно вперёд. Внутри групп относительный порядок сохраняется, то
    есть скор по-прежнему решает всё, кроме одного: монета со своим
    обстоятельством уходит вниз, а не исчезает.

    Отдельная функция, а не флаг в flow_order: номер звезды на орбите
    и позиция на карточке считаются от ЧИСТОГО порядка по скору, и
    менять его под показ значило бы разъехаться с ними молча.
    """
    order = flow_order(candidates)
    return ([c for c in order if coin_window(c)["open"]]
            + [c for c in order if not coin_window(c)["open"]])


def flow_leader(candidates: list[Candidate]) -> Candidate | None:
    """Лидер прогона FLOW — первая монета того же порядка.

    Считается ЧЕРЕЗ flow_order, а не отдельным max(), намеренно.
    Результат сегодня совпадает (sorted устойчив, max берёт первый из
    равных), но совпадает случайно: это два независимых правила,
    которые обязаны давать один ответ. Выражая одно через другое, мы
    делаем совпадение обязательным, а не удачным — правку правила
    порядка невозможно забыть протащить в выбор лидера.
    """
    order = flow_order(candidates)
    return order[0] if order else None


def case_counts(candidates: list[Candidate]) -> dict[str, int]:
    """Сколько монет в каждом подкейсе, по КОРОТКОМУ ключу.

    Короткий ключ, потому что единственный потребитель — лента узлов
    (FLOW_NODES), где подкейсы названы без префикса. Считать с
    префиксом и резать его у потребителя значит завести второе место,
    где живёт знание о префиксе.
    """
    out: dict[str, int] = {}
    for c in flow_candidates(candidates):
        k = case_key(case_of(c))
        out[k] = out.get(k, 0) + 1
    return out


# Порог заметности объёма для строки «объём · flow». Не порог
# качества сигнала: величина та же, что читает карточка монеты
# (v1h/v4h/v1d), а не отдельная метрика.
BIG_VOLUME_X = 30.0


def big_volume(candidates: list[Candidate],
               threshold: float = BIG_VOLUME_X) -> list[dict]:
    """Монеты FLOW с объёмом ≥ threshold× на любом из трёх ТФ.

    Отсортированы по максимальному множителю, он же и подписывается
    в строке.

    Тикер отдаётся без экранирования: HTML-экранирование — забота
    того, кто вставляет строку в разметку, и слой аналитики о
    разметке знать не должен.
    """
    out = []
    for c in flow_candidates(candidates):
        d = card_data(c)
        best = max(d.get("v1h") or 0, d.get("v4h") or 0, d.get("v1d") or 0)
        if best >= threshold:
            out.append({
                "t": base_symbol(c.symbol),
                "x": round(best, 1),
                "cap": fmt_cap(d["cap"]),
            })
    out.sort(key=lambda r: -r["x"])
    return out
