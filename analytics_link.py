"""Связка разлока и открытого интереса (Р-12). Отметка, не вердикт.

Опасна СВЯЗКА, а не каждая часть. По отдельности растущий OI — всего
лишь накопление, а транш на монете с большим оборотом переваривается
за часы. Вместе — конструкция для выноса: плечо сверху, предложение
снизу, и одно кормит другое.

Случай, на котором это увидели (SANTOS). Открытый интерес рос
месяцами при плоской и сползающей цене — с миллиона до 3.35; в те же
сутки приходил транш примерно на 17.5% капитализации; монета пробила
собственное дно.

Портрет ZEC добавил к этому направление чтения (Р-8). Само по себе
«OI высокий» не приговор: у монеты добычи плечо должно быть НА ДНЕ
после слома, и памп идёт с пустого. Опасен именно НАБРАННЫЙ и ещё не
слитый интерес — тот, что держится (oi_held) и вырос (oi_rise).
Поэтому связка читает не уровень OI, а его удержание рядом с датой
транша.

Чего здесь НЕТ и не будет: штрафа к скору и вердикта «опасно».
Нулевой раздел: пункты этого документа не трогают скор. Наружу идёт
отметка с числами — дни до транша, доля флоата, состояние плеча, —
а решение принимает человек.

Обе величины уже посчитаны: OI приходит из flow-контекста
(analytics_momentum.star_oi), транш — из unlocks.json
(analytics_unlocks.for_symbol). Новых запросов ноль.
"""

from __future__ import annotations

# Окно совпадения: транш ближе этого числа дней считается «рядом».
# Пять дней — то же окно, что у календаря частокола (Р-7), и по той
# же причине: рынок отрабатывает известную дату заранее, а не в день
# события. Держать два разных горизонта внимания в одном проекте
# значило бы объяснять разницу каждый раз, когда числа разойдутся.
UNLOCK_NEAR_DAYS = 5

# Плечо считается НАБРАННЫМ при обоих условиях сразу.
# rise_x — во сколько раз OI вырос от базы своего окна; held_pct —
# какая доля набранного не слита. Порог удержания высокий намеренно:
# слитое плечо перед траншем — это уже не связка, а разряженный
# инструмент (портрет ZEC), и путать их нельзя.
OI_RISE_X = 1.5
OI_HELD_PCT = 70.0


def unlock_leverage_link(star: dict) -> dict:
    """Отметка связки по готовым полям звезды.

    Возвращает пустой словарь, если хотя бы одной половины нет: связка
    из одной части не бывает, а «нет данных» и «нет связки» на экране
    обязаны выглядеть по-разному — вторую покажет отсутствие отметки
    при заполненных числах, первую пробел в самих числах.
    """
    days = star.get("unlockDays")
    rise = star.get("oiRise")
    held = star.get("oiHeld")
    if days is None or rise is None or held is None:
        return {}

    try:
        days_i = int(days)
        rise_f = float(rise)
        held_f = float(held)
    except (TypeError, ValueError):
        return {}

    if days_i < 0 or days_i > UNLOCK_NEAR_DAYS:
        return {}
    if rise_f < OI_RISE_X or held_f < OI_HELD_PCT:
        return {}

    # Доля транша — тем числом, какое заполнено. Флоат честнее:
    # он говорит, насколько вырастет ТОРГУЕМОЕ предложение, а доля
    # эмиссии — сколько токенов существует. Первое двигает цену.
    share = star.get("unlockPctFloat")
    share_key = "флоата"
    if share is None:
        share = star.get("unlockPctSupply")
        share_key = "эмиссии"

    when = ("сегодня" if days_i == 0 else
            "завтра" if days_i == 1 else f"через {days_i} дн")
    note = f"плечо набрано (×{rise_f:.1f}, держится {held_f:.0f}%), транш {when}"
    if share is not None:
        note += f" на {float(share):.0f}% {share_key}"

    return {
        "linkDays": days_i,
        "linkRise": round(rise_f, 2),
        "linkHeld": round(held_f, 1),
        "linkShare": (round(float(share), 1) if share is not None else None),
        "linkNote": note,
    }
