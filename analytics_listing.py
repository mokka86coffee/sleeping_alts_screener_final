"""Состояние листинга (Р-32). Что важнее разлока.

Разлок — навес: предложение приходит в стакан, и цена может его
переварить. Делистинг убирает сам стакан, и позицию закрывают
принудительно по цене, которую выбирает не владелец.

Дефект, из-за которого модуль появился (25.08.2026): STORJ стоял в
книге и держался скринером в списке ЗАРЯЖЕННЫХ НА СЖИМ — фандинг
отрицательный 28 баров. На деле Storj Labs с 26.07 в банкротстве,
Binance объявила делистинг, фьючерсы закрывались принудительным
расчётом 26.08. Отрицательный фандинг означал не «шортов вынесут», а
«все выходят до расчёта». Скринер читал цену, объём и фандинг — и не
видел юридического события, потому что такого входа данных не было.

ОТСУТСТВИЕ ВХОДА ДАННЫХ — НЕ ТО ЖЕ, ЧТО ОТСУТСТВИЕ РИСКА.

── Почему четыре биржи и почему по-разному ──

Каждая площадка сообщает о делистинге СВОИМ способом, общего поля нет.
Поэтому нормализаторы отдельные, а сверху — универсальный запасной
способ через сравнение со снимком.

  Binance  меняет deliveryDate у бессрочного с заглушки 2100 года на
           реальное время расчёта. Удобнейший случай: срок виден
           заранее и прямо числом.
  Bybit    держит status и deliveryTime в справочнике инструментов.
  OKX      при делистинге ПРОСТО УБИРАЕТ инструмент из выдачи — в их
           документации сказано прямо: инструмент станет недоступен.
           Отдельного поля со сроком нет, ловится исчезновением.
  BingX    поле статуса в справочнике контрактов; ЭНДПОИНТ И ИМЕНА
           ПОЛЕЙ ТРЕБУЮТ СВЕРКИ — надёжного описания у меня не было,
           догадку в код не ставлю.

── Сроки предупреждения различаются в разы ──

Это важнее самих полей. По сводным данным: Binance по фьючерсам даёт
примерно от суток до трёх, Bybit пять-семь дней, OKX около недели, а
мелкие площадки, включая BingX, иногда предупреждают за считаные часы.
Аварийный делистинг при взломе или предписании регулятора приходит
вовсе без предупреждения.

Два следствия. Опрашивать надо ЧАСТО, иначе на быстрой площадке
узнаёшь постфактум. И для монет, живущих только на мелких площадках,
датчик даёт мало времени ПО СУЩЕСТВУ, а не по нашей нерасторопности —
это учитывается размером позиции, а не ожиданием невозможного.
"""

from __future__ import annotations

PERPETUAL_NEVER = 4_133_404_800_000   # заглушка Binance: 31.12.2100

DELIST_URGENT_DAYS = 3      # закрывать самому, пока цена своя
DELIST_NEAR_DAYS = 14       # вход запрещён, позицию сокращать

# Держим списком, чтобы источник был виден рядом с кодом.
ENDPOINTS = {
    "binance": "https://fapi.binance.com/fapi/v1/exchangeInfo",
    "bybit":   "https://api.bybit.com/v5/market/instruments-info?category=linear",
    "okx":     "https://www.okx.com/api/v5/public/instruments?instType=SWAP",
    "bingx":   None,  # СВЕРИТЬ: справочник бессрочных контрактов
}


def _norm(sym: str) -> str:
    """Общий вид тикера: OKX пишет BTC-USDT-SWAP, остальные BTCUSDT."""
    return sym.upper().replace("-SWAP", "").replace("-", "")


def read_binance(payload: dict, now_ms: int) -> dict:
    """{тикер: время расчёта} из deliveryDate.

    Поле меняется в тот же момент, когда публикуется объявление —
    быстрее, чем отрисуется страница, и в готовом виде.
    """
    out = {}
    for s in (payload or {}).get("symbols", []):
        if s.get("contractType") != "PERPETUAL":
            continue
        try:
            dd = int(s.get("deliveryDate"))
        except (TypeError, ValueError):
            continue
        if now_ms < dd < PERPETUAL_NEVER:
            out[_norm(s["symbol"])] = dd
    return out


def read_bybit(payload: dict, now_ms: int) -> dict:
    """status плюс deliveryTime. Ноль означает «идёт, но не торгуется»."""
    out = {}
    for s in ((payload or {}).get("result") or {}).get("list", []):
        sym = _norm(s.get("symbol", ""))
        if not sym:
            continue
        try:
            dt = int(s.get("deliveryTime") or 0)
        except (TypeError, ValueError):
            dt = 0
        if now_ms < dt < PERPETUAL_NEVER:
            out[sym] = dt
        elif s.get("status") and s["status"] != "Trading":
            out[sym] = 0
    return out


def read_okx(payload: dict, now_ms: int) -> dict:
    """state плюс expTime.

    Основную работу по этой площадке делает сравнение со снимком:
    делистнутый инструмент просто пропадает, и ловить в нём нечего.
    """
    out = {}
    for s in (payload or {}).get("data", []):
        sym = _norm(s.get("instId", ""))
        if not sym:
            continue
        try:
            exp = int(s.get("expTime") or 0)
        except (TypeError, ValueError):
            exp = 0
        if now_ms < exp < PERPETUAL_NEVER:
            out[sym] = exp
        elif s.get("state") and s["state"] != "live":
            out[sym] = 0
    return out


def snapshot(payloads: dict) -> set:
    """Тикеры, торгуемые сейчас, по всем площадкам сразу.

    Хранить между прогонами: это эталон для следующего сравнения.
    """
    out = set()
    for venue, p in (payloads or {}).items():
        if venue == "binance":
            out |= {_norm(s["symbol"]) for s in (p or {}).get("symbols", [])
                    if s.get("contractType") == "PERPETUAL"}
        elif venue == "bybit":
            out |= {_norm(s["symbol"]) for s in
                    ((p or {}).get("result") or {}).get("list", [])}
        elif venue == "okx":
            out |= {_norm(s["instId"]) for s in (p or {}).get("data", [])}
    return out


def disappeared(prev: set, now: set) -> set:
    """Тикеры, пропавшие с прошлого прогона.

    ЕДИНСТВЕННЫЙ способ, работающий на всех площадках: поля у всех
    разные, а исчезновение выглядит одинаково. Ловит и аварийный
    делистинг, у которого предупреждения нет вовсе.

    ЛОЖНОЕ СРАБАТЫВАНИЕ: сбой запроса или обрезанный ответ выглядят
    как исчезновение всего разом. Поэтому сначала проверяем
    правдоподобие снимка по размеру — паническое закрытие живой
    позиции из-за сбоя сети обошлось бы дороже пропущенного
    делистинга.
    """
    if not prev or not now:
        return set()
    if len(now) < len(prev) * 0.7:
        return set()      # пропала треть — это сбой, а не рынок
    return prev - now


def listing_state(symbol: str, schedule: dict, gone: set, now_ms: int,
                  tags: dict | None = None) -> dict | None:
    """Состояние листинга одной монеты. None — всё в порядке.

    Ступени по СРОЧНОСТИ, а не по вероятности: если делистинг
    объявлен, вероятность равна единице, остаётся только время.
    """
    tags = tags or {}
    sym = _norm(symbol)

    if sym in gone:
        return {"level": "инструмент исчез", "act": "проверить руками СЕЙЧАС",
                "why": ("тикер пропал из справочника — так выглядит "
                        "делистинг без предупреждения; убедиться, что это не "
                        "сбой, и если нет — закрывать"),
                "settle_ms": None, "days": None}

    if sym in schedule:
        dd = schedule[sym]
        if not dd:
            return {"level": "торговля остановлена", "act": "вход запрещён",
                    "why": "инструмент не в торговом статусе — стакана нет",
                    "settle_ms": None, "days": None}
        days = (dd - now_ms) / 86_400_000.0
        if days <= DELIST_URGENT_DAYS:
            level, act = "СРОЧНО", "закрыть самому"
            why = (f"расчёт через {days:.1f} дн. Позиции закрываются "
                   f"автоматически, цену выхода выбирает площадка: у Bybit "
                   f"это средняя индексная за последние полчаса, у Binance "
                   f"своя процедура. К сроку ликвидность падает, "
                   f"проскальзывание растёт")
        elif days <= DELIST_NEAR_DAYS:
            level, act = "делистинг близко", "вход запрещён, позицию сокращать"
            why = f"торги закрываются через {days:.1f} дн — стакан исчезнет"
        else:
            level, act = "делистинг объявлен", "новых входов не делать"
            why = f"торги закрываются через {days:.0f} дн"
        return {"level": level, "act": act, "why": why,
                "settle_ms": dd, "days": round(days, 1)}

    tag = tags.get(sym)
    if tag:
        return {"level": "наблюдательная метка", "act": "размер уменьшить",
                "why": (f"площадка пометила монету как повышенно рисковую "
                        f"({tag}) — предупреждение о возможном делистинге, не "
                        f"приговор: метку снимают, если проект выправляется"),
                "settle_ms": None, "days": None}
    return None


def veto(state: dict | None) -> bool:
    """Жёстче, чем у разлока: транш пересидеть можно, закрытие — нет."""
    return bool(state) and state["level"] != "наблюдательная метка"


