def _state_path(base: Path) -> Path:
    """Когда что делали в последний раз. Рядом с ручными файлами, в
    корне, — той же логикой, что reservoir.json и events.json."""
    return base / "manual_state.json"


def _load(base: Path) -> dict:
    try:
        with open(_state_path(base), encoding="utf-8") as f:
            d = json.load(f)
        return d if isinstance(d, dict) else {}
    except (OSError, ValueError):
        return {}


def mark_done(key: str, base: Path, today: date | None = None) -> None:
    """Отметить дело сделанным. Зовётся руками после работы."""
    st = _load(base)
    st[key] = str(today or date.today())
    try:
        with open(_state_path(base), "w", encoding="utf-8") as f:
            json.dump(st, f, ensure_ascii=False, indent=1)
    except OSError:
        pass


def due(base: Path, today: date | None = None) -> list[dict]:
    """Дела, чей срок ПОДОШЁЛ. Только они, и ни одного лишнего.

    Дело без отметки считается просроченным с самого начала: если файла
    состояния нет, значит вручную ещё ничего не делали, и напомнить
    надо обо всём. Молчать в этом случае было бы худшим вариантом —
    именно так reservoir.json и пролежал с одной записью.
    """
    today = today or date.today()
    st = _load(base)
    out = []
    for t in TASKS:
        last = st.get(t["key"])
        age = None
        if last:
            try:
                age = (today - datetime.strptime(last, "%Y-%m-%d").date()).days
            except ValueError:
                age = None
        if age is None or age >= t["every"]:
            out.append({**t, "age": age, "last": last})
    out.sort(key=lambda t: (t["every"], t["key"]))
    return out


def report(base: Path, today: date | None = None, log=print) -> int:
    """Печать в начале прогона. Возвращает число подошедших дел.

    Ничего не подошло — печатается ОДНА строка, а не тишина: молчание
    неотличимо от поломки напоминалки, и через месяц никто не помнит,
    работает она вообще или нет.
    """
    items = due(base, today)
    if not items:
        log("→ Ручное: всё в срок")
        return 0

    log(f"\n{'─' * 60}")
    log(f"→ РУЧНОЕ: подошёл срок у {len(items)} — сделать до следующего прогона")
    for t in items:
        when = ("ни разу" if t["last"] is None
                else f"{t['age']} дн назад" if t["age"] is not None
                else "дата непонятна")
        log(f"   · {t['what']}")
        log(f"     раз в {t['every']} дн · последний раз {when}")
        log(f"     {t['how']}")
        log(f"     зачем: {t['why']}")
    log(f"{'─' * 60}\n")
    return len(items)
