# Порядок, в котором пробелы показываются на экране: сначала то, без
# чего выводы получаются неверными, а не просто неполными.
FIELD_ORDER = tuple(f["key"] for f in MANUAL_FIELDS)

_BY_KEY = {f["key"]: f for f in MANUAL_FIELDS}


def _filled(value) -> bool:
    """Заполнено ли поле.

    Пустая строка, пустой список и None — не заполнено. Ноль считается
    заполненным: ноль полок или нулевая база это ответ, а не пропуск.
    """
    if value is None:
        return False
    if isinstance(value, str):
        return bool(value.strip())
    if isinstance(value, (list, tuple, dict)):
        return len(value) > 0
    return True


def missing(rec: dict) -> list[str]:
    """Ключи полей, которых в записи не хватает.

    Порядок сохраняется из FIELD_ORDER, чтобы на экране пробелы шли
    одинаково у всех монет и глаз к нему привыкал.
    """
    if not isinstance(rec, dict):
        return list(FIELD_ORDER)
    return [k for k in FIELD_ORDER if not _filled(rec.get(k))]


def labels(keys: list[str]) -> list[str]:
    """Человеческие подписи для набора ключей."""
    return [_BY_KEY[k]["label"] for k in keys if k in _BY_KEY]


def describe(key: str) -> dict:
    """Полное описание поля — для подсказки при заполнении."""
    return dict(_BY_KEY.get(key) or {})


def stats(store: dict) -> dict:
    """Сколько пробелов по журналу и где их больше.

    Нужно для верхней строки оверлея: одно число «сколько всего» и
    самое частое незаполненное поле. Если у всех монет не хватает
    одного и того же — заполнять надо его, а не ходить по монетам.
    """
    per_field: dict[str, int] = {k: 0 for k in FIELD_ORDER}
    coins = 0
    gaps = 0
    for symbol, rec in (store or {}).items():
        if symbol.startswith("_") or not isinstance(rec, dict):
            continue
        coins += 1
        miss = missing(rec)
        gaps += len(miss)
        for k in miss:
            per_field[k] += 1
    if not coins:
        return {}

    worst = max(per_field.items(), key=lambda kv: kv[1])
    return {
        "coins": coins,
        "gaps": gaps,
        "full": sum(1 for k in per_field if per_field[k] == 0),
        "worst": {"key": worst[0],
                  "label": _BY_KEY[worst[0]]["label"],
                  "n": worst[1]},
        "per_field": per_field,
    }
