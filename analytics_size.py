"""Размер позиции как правило, а не как привычка (Р-15, с Р-4).

Записано «тысяча на монету, добор пятьсот». Но монеты не равны: у
одной флоат 26% и инсайдерский транш через месяц, у другой вестинг
закрыт и живой спот. Одинаковый размер на обеих — молчаливая ставка,
что риск одинаков. Он не одинаков.

Правило грубое намеренно. Три ступени, названные причины, ноль
моделей риска: волатильность портфеля мы не считаем и считать не
собираемся. Задача не в точности, а в том, чтобы разница между
монетами перестала быть невысказанной.

Формулировка Р-4, которую держим рядом: проект не защищает от сквиза
и не может. Он должен помогать НЕ ОКАЗЫВАТЬСЯ в позиции, которую
сквиз способен убить. Размер позиции и плечо — единственные
переменные, целиком во власти человека; всё остальное в этом
документе только описывает рынок.

Два уровня признаков, и они складываются.

РЫНОЧНЫЕ (Р-4) — общие для всей выборки, приходят из разрешения:
выходные (тонкий стакан), раздутый суммарный OI, идущий каскад.
МОНЕТНЫЕ (Р-15) — свои у каждой: низкий флоат, близкий инсайдерский
транш, связка плеча с траншем (Р-12), листинговый распил вместо
цикла (ручное поле listing_kind).

Ступень понижается на одну за КАЖДЫЙ сработавший уровень, не за
каждый признак: иначе три монетных признака сразу выбрасывали бы
позицию в ноль, а это уже вердикт «не входить», которого правило не
выносит. Ниже четверти ступень не опускается — «слишком мало, чтобы
входить» решает человек, а не таблица.
"""

from __future__ import annotations

# База и добор — записанные ранее величины, вынесены в имена, чтобы
# правило можно было пересчитать в других деньгах одной правкой.
BASE_POSITION_USD = 1000.0
ADD_POSITION_USD = 500.0

# Доли ступеней. Три, а не пять: см. docstring — правило грубое.
TIERS = ((1.0, "полный"), (0.5, "половина"), (0.25, "четверть"))

# Низкий флоат: сколько процентов обращения считать навесом. 30 —
# прикидка того же порядка, что и прочие пороги документа; заменится
# процентилями по выборке, когда накопится история (Р-9).
LOW_FLOAT_PCT = 30.0

# Транш ближе этого числа дней — монетный признак. Тот же горизонт,
# что у Р-6, Р-7, Р-11 и Р-12: один на весь проект.
UNLOCK_NEAR_DAYS = 5


def position_size(star: dict, permission: dict | None = None) -> dict:
    """Ступень размера для монеты. Не вердикт — рекомендация с причинами.

    star — словарь звезды; permission — market_permission целиком
    (рыночные признаки берутся из его составляющих, а не считаются
    заново: у разрешения один источник истины на прогон).

    Возвращает {"tier", "usd", "add", "why", "steps"}. Пустой список
    причин при полной ступени — норма: понижать нечему.
    """
    why: list[str] = []
    steps = 0

    # ── Рыночный уровень (Р-4) ──
    parts = ((permission or {}).get("parts") or {})
    market_hits = []
    if (parts.get("weekend") or {}).get("warn"):
        market_hits.append("выходные — тонкий стакан")
    if (parts.get("oi") or {}).get("warn"):
        market_hits.append("суммарный OI раздут")
    if (parts.get("cascade") or {}).get("warn"):
        market_hits.append("каскад идёт")
    if market_hits:
        steps += 1
        why.append("рынок: " + ", ".join(market_hits))

    # ── Монетный уровень (Р-15) ──
    coin_hits = []
    fl = star.get("floatPct")
    try:
        if fl is not None and float(fl) < LOW_FLOAT_PCT:
            coin_hits.append(f"флоат {float(fl):.0f}% — навес сверху")
    except (TypeError, ValueError):
        pass

    days = star.get("unlockDays")
    try:
        near = days is not None and 0 <= int(days) <= UNLOCK_NEAR_DAYS
    except (TypeError, ValueError):
        near = False
    if near and star.get("unlockIns"):
        coin_hits.append(f"инсайдерский транш через {int(days)} дн")
    elif near:
        coin_hits.append(f"транш через {int(days)} дн")

    if star.get("linkNote"):
        coin_hits.append("связка плеча с траншем")

    # Распил — ручное поле: у него «упала на 96%» не значит «пережила
    # цикл», толпы там не было и возвращаться некому.
    if str(star.get("listingKind") or "").strip().lower().startswith("распил"):
        coin_hits.append("листинговый распил, не цикл")

    if coin_hits:
        steps += 1
        why.append("монета: " + ", ".join(coin_hits))

    idx = min(steps, len(TIERS) - 1)
    share, label = TIERS[idx]
    return {
        "tier": label,
        "usd": round(BASE_POSITION_USD * share),
        "add": round(ADD_POSITION_USD * share),
        "why": why,
        "steps": steps,
    }
