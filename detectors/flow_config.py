# ─── Свежесть зоны [KOMA] ───────────────────────────────────
# От белого пузыря на дне до выноса прошло ~200 дней. Абсолютный
# порог давности выбросил бы этот кейс из скора целиком.
#
# Событие стареет. Зона, которую оно разметило, — нет: она живёт,
# пока цена её не пробила. Возраст обнуляется при каждом успешном
# тесте уровня.

ZONE_TEST_TOUCH_PCT = 0.04      # заход в пределах 4% — тест зоны
ZONE_TEST_HOLD_PCT = 0.02       # уход ниже этой доли — кандидат на пробой
