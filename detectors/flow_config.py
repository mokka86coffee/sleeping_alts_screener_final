# ─── Подтверждение пробоя [MMT] ─────────────────────────────
# Семь месяцев базы гарантированно содержат заходы под уровень.
# Мгновенный пробой по тени убивал такие зоны в первый же месяц,
# и монета выпадала из семейства целиком — ни churn, ни spring
# не собирались, потому что зон не оставалось.
#
# Тень под уровнем в длинной базе — это тест: сходили за
# ликвидностью и вернулись. Пробой — это когда цена ушла и
# ОСТАЛАСЬ. Поэтому считаем по закрытиям и требуем серии.

ZONE_BREAK_BARS = 3         # столько закрытий подряд под зоной = пробой
ZONE_BREAK_DEEP_PCT = 0.08  # уход глубже — пробой сразу, без подтверждения


# ─── Плато над зоной [KOMA, MMT] ────────────────────────────
# Плато закрывает фигуру: одиночное поглощение говорит «здесь
# столкнулись», но не говорит, кто победил. Победителя определяет
# то, что происходит потом.
#
# Но это верно НЕ для всех подкейсов, и прогон это показал:
# из семи ненулевых churn полного множителя не получил никто,
# spring дал два ненулевых значения на 224 монеты. Причина —
# PLATEAU_FULL_BARS = 60 недостижимо почти никогда, а отсутствие
# плато резало вклад более чем вдвое.
#
# Разведено по смыслу:
#   churn — плато обязательно. Без удержания над зоной победитель
#           столкновения неизвестен, это заготовка, а не фигура.
#   spring — плато НЕ обязательно. Там сжатие само по себе фигура,
#           а долгое стояние — признак затухания, а не силы.

PLATEAU_MIN_BARS = 12       # минимум дней над зоной без пробоя
PLATEAU_MAX_RANGE = 0.35    # ширина диапазона к цене
