# уложился в 0.479..0.509 — три процентных пункта на всю выборку,
# включая и растущие монеты, и сливающиеся. Сдвиг между базовым и
# поздним окном ВНУТРИ одной монеты — величина того же порядка,
# что шум оценки, то есть доли пункта.
#
# Прежние 0.05 и промежуточные 0.025 недостижимы физически: они
# требуют смены режима торговли целиком. Восемь десятых пункта —
# это уже заметное смещение состава потока, и при этом порог
# достижим на реальных данных.
#
# Подкейс при таком пороге становится чувствительным, поэтому
# доверять ему как самостоятельному поводу нельзя — это и
# отражает низкий CAP_TAKER = 72.
TAKER_SHIFT_MIN = 0.008

TAKER_STABILITY_MAX = 0.09      # разброс доли внутри окна
TAKER_MIN_QUOTE_VOL = 300_000   # медиана дневного оборота позднего окна

# Минимум событий в контексте монеты.
#
# Не зон — событий. Доля покупок считается по любым барам, поэтому
# формально подкейс работает даже там, где ядро не нашло ни одной
# аномалии объёма. Но такая монета не даёт материала для суждения
# о составе потока: LITEUSDT прошла с тремя событиями за всю
# историю и нулём зон, набрав 47 баллов на сдвиге, который целиком
# объясняется парой заявок.
#
# Это фильтр области определения, а не строгости. Величина сдвига
# может быть какой угодно — если рынка нет, мерить нечего.
#
# Двадцать выбрано по разбросу: типичная монета даёт 90–160
# событий, и порог отсекает только вырожденные случаи, не трогая
# честные — CAKE со 107 событиями и нулём зон проходит.
TAKER_MIN_EVENTS = 20


